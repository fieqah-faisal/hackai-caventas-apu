def _json_text(data: Any) -> str:
    return json.dumps(data, indent=2, ensure_ascii=False) + "\n"


def _has_conditions(batch: dict[str, Any]) -> bool:
    return bool(batch.get("branches")) or any(e.get("when") for e in batch["entries"])


def _attack_csv(rows: list[dict[str, Any]]) -> str:
    buffer = io.StringIO()
    columns = ["technique_id", "technique_name", "tactic", "status", "record_ids", "confidence",
               "reasoning", "missing_evidence", "url"]
    writer = csv.DictWriter(buffer, fieldnames=columns, lineterminator="\n")
    writer.writeheader()
    for row in rows:
        writer.writerow({**row, "record_ids": " ".join(row["record_ids"])})
    return buffer.getvalue()


def _timeline_md(scenario: dict[str, Any]) -> str:
    lines = [
        f"# Ground-truth timeline - {scenario['title']}",
        "",
        f"> {NOTE} Evaluator-only.",
        "",
        "| Time (+08:00) | Side | What happened | Records | ATT&CK |",
        "|---|---|---|---|---|",
    ]
    for when, side, what, records, technique in scenario["ground_truth_timeline"]:
        lines.append(f"| {when} | {side} | {what} | {records} | {technique} |")
    lines += ["", "## Checkpoints", ""]
    for cp in scenario["checkpoints"]:
        lines.append(f"- **{cp['id']}** (after batch {cp['after_batch']}): {cp['intent']}")
    return "\n".join(lines) + "\n"


def _demo_path(scenario: dict[str, Any]) -> tuple[dict[str, bytes], str]:
    """Pre-render later batches for the documented demo approvals."""
    files: dict[str, bytes] = {}
    results: list[dict[str, Any]] = []
    revealed: set[str] = set()
    evidence_times: list[str] = []
    notes = [
        f"# Demo path - {scenario['title']}",
        "",
        f"> {NOTE}",
        "",
        "Upload `../batch_01.json`, then approve and execute these actions in order with "
        f"`SIMULATOR_PROFILE={scenario['profile']}`. If you approve different actions, the "
        "evaluation harness renders the matching batches instead.",
        "",
    ]
    for batch_no, batch in enumerate(scenario["batches"], start=1):
        if batch_no > 1:
            records, branch = render_batch(scenario, batch_no, results, revealed)
            files[f"batch_{batch_no:02d}.json"] = serialise(records, "json")
            notes.append(f"Then upload `batch_{batch_no:02d}.json` (branch `{branch}`).")
            notes.append("")
        else:
            records, _ = render_batch(scenario, 1, results, revealed)
        revealed |= {r["record_id"] for r in records}
        evidence_times += [r["event_time"] for r in records]
        if batch_no - 1 < len(scenario.get("demo_path", [])):
            notes.append(f"After batch {batch_no}, approve and execute:")
            notes.append("")
            for tool, target in scenario["demo_path"][batch_no - 1]:
                clock = engine.simulated_clock(evidence_times, [r["simulated_at"] for r in results])
                result = engine.simulate(tool, target, simulated_at=clock, history=results,
                                         profile=scenario["profile"])
                results.append(result)
                notes.append(f"- `{tool}` on `{target}` at {clock.strftime('%H:%M')} -> "
                             f"{result['execution_status']} / {result['validation_status']}: "
                             f"{result['observed_effect']}")
            notes.append("")
    return files, "\n".join(notes)


def build(root: Path = ROOT) -> list[Path]:
    """Write every generated file under ``root``; returns the paths written."""
    written: list[Path] = []

    def write(path: Path, content: str | bytes) -> None:
        path.parent.mkdir(parents=True, exist_ok=True)
        if isinstance(content, str):
            path.write_text(content, encoding="utf-8", newline="\n")
        else:
            path.write_bytes(content)
        written.append(path)

    shared = root / "shared"
    if shared.exists():
        shutil.rmtree(shared)
    env = engine.load_environment()
    write(shared / "asset_inventory.json", _json_text({
        "note": f"{NOTE} Agent-visible organisation context.",
        "organisation": env["organisation"],
        "hosts": env["hosts"],
        "accounts": env["accounts"],
    }))
    write(shared / "action_catalog.json", _json_text({
        "note": f"{NOTE} The only actions the simulator will run.",
        "simulator_version": catalog.SIMULATOR_VERSION,
        "tools": catalog.describe(),
    }))

    index = []
    for scenario in all_scenarios():
        sid = scenario["scenario_id"]
        base = root / sid
        if base.exists():
            shutil.rmtree(base)
        agent, evaluator = base / "agent_inputs", base / "evaluator_only"
        write(agent / "case.json", _json_text(scenario["case"]))
        for batch_no, batch in enumerate(scenario["batches"], start=1):
            if batch_no == 1 or not _has_conditions(batch):
                records, _ = render_batch(scenario, batch_no, [], set())
                write(agent / f"batch_{batch_no:02d}.{batch['format']}",
                      serialise(records, batch["format"]))
        if scenario.get("demo_path"):
            files, notes = _demo_path(scenario)
            for name, content in files.items():
                write(agent / "demo_path" / name, content)
            write(agent / "demo_path" / "DEMO_PATH.md", notes + "\n")
        stored = {k: v for k, v in scenario.items() if k not in {"demo_path", "ground_truth_timeline"}}
        write(evaluator / "scenario.json", _json_text({"note": NOTE, **stored}))
        write(evaluator / "attack_mapping.csv", _attack_csv(scenario["attack_mapping"]))
        write(evaluator / "ground_truth_timeline.md", _timeline_md(scenario))
        index.append({"scenario_id": sid, "kind": scenario["kind"], "title": scenario["title"],
                      "checkpoints": len(scenario["checkpoints"])})
    write(root / "index.json", _json_text({"note": NOTE, "scenarios": index}))
    return written


if __name__ == "__main__":
    paths = build()
    print(f"wrote {len(paths)} files under {ROOT}")
