# --- helpers -----------------------------------------------------------------


def t(day: str, hm: str) -> str:
    return f"{day}T{hm if hm.count(':') == 2 else hm + ':00'}+08:00"


def sha(label: str) -> str:
    return hashlib.sha256(f"caventas-synthetic|{label}".encode()).hexdigest()


def rec(
    rid: str,
    when: str,
    event_type: str,
    source: str,
    host: Optional[str] = None,
    account: Optional[str] = None,
    **data: Any,
) -> dict[str, Any]:
    """One agent-visible evidence record in the backend's upload shape."""
    record: dict[str, Any] = {"event_time": when, "event_type": event_type}
    if host:
        record["host"] = host
    if account:
        record["account"] = account
    record["source"] = source
    record.update(data)
    record["record_id"] = rid
    return record


def entry(record: dict[str, Any], when: Optional[dict] = None) -> dict[str, Any]:
    return {"record": record, "when": when}


def done(tool, target, before=None, service=None) -> dict:
    spec: dict[str, Any] = {"tool": tool, "target": target}
    if before:
        spec["before"] = before
    if service:
        spec["service"] = service
    return {"done": spec}


def failed(tool, target, before=None, service=None) -> dict:
    return {"failed": done(tool, target, before, service)["done"]}


def NOT(cond: dict) -> dict:
    return {"not": cond}


def ALL(*conds: dict) -> dict:
    return {"all": list(conds)}


def ANY(*conds: dict) -> dict:
    return {"any": list(conds)}


def revealed(rid: str) -> dict:
    return {"revealed": rid}


def action(aid, tools, targets, why, key_records=(), when=None, satisfied_if_done=True,
           informational=False) -> dict:
    return {
        "id": aid,
        "tools": list(tools) if isinstance(tools, (list, tuple)) else [tools],
        "targets": list(targets) if isinstance(targets, (list, tuple)) else [targets],
        "why": why,
        "key_records": list(key_records),
        "satisfied_if_done": satisfied_if_done,
        "informational": informational,
        "when": when,
    }


def forbid(fid, tools, targets, gate, why, when=None) -> dict:
    return {
        "id": fid,
        "tools": list(tools) if isinstance(tools, (list, tuple)) else [tools],
        "targets": list(targets),
        "gate": gate,
        "why": why,
        "when": when,
    }


def question(qid, keywords, why, gate=False, when=None) -> dict:
    return {"id": qid, "any": list(keywords), "why": why, "gate": gate, "when": when}


def tool_policy(pid, tool, policy, why) -> dict:
    return {"id": pid, "tool": tool, "policy": policy, "why": why}


def trigger_policy(pid, policy, keywords, why, when=None) -> dict:
    return {"id": pid, "trigger": policy, "keywords": list(keywords), "why": why, "when": when}


def stage(preferred, acceptable=(), when=None) -> dict:
    return {"preferred": list(preferred), "acceptable": list(acceptable), "when": when}


def mapping(tid, name, tactic, status, records, confidence, reasoning, missing="") -> dict:
    return {
        "technique_id": tid,
        "technique_name": name,
        "tactic": tactic,
        "status": status,
        "record_ids": list(records),
        "confidence": confidence,
        "reasoning": reasoning,
        "missing_evidence": missing,
        "url": "https://attack.mitre.org/techniques/" + tid.replace(".", "/") + "/",
    }


