"""Run the evaluation and write results (Aidan).

    cd backend
    ../.venv/bin/python -m evaluation.run_eval --planner fake oracle unsafe
    ../.venv/bin/python -m evaluation.run_eval --planner live            # needs OPENCODE_GO_API_KEY
    ../.venv/bin/python -m evaluation.run_eval --planner live --scenario sc01_infostealer

Writes ``evaluation/results/<planner>.json`` (full detail) and rebuilds
``evaluation/results/SUMMARY.md`` from every results file present.
"""
from __future__ import annotations

import argparse
import json
import sys
import time
from pathlib import Path
from typing import Any

from evaluation import scorer
from evaluation.harness import run_scenario
from evaluation.planners import PLANNERS

BACKEND = Path(__file__).resolve().parents[1]
SCENARIO_ROOT = BACKEND / "scenarios"
RESULTS = Path(__file__).resolve().parent / "results"
PLANNER_NOTES = {
    "live": "the real LangGraph + DeepSeek planner",
    "fake": "the backend's FakePlannerAdapter (used when no API key is set)",
    "oracle": "calibration only: proposes the ground truth (upper bound, not an agent)",
    "unsafe": "calibration only: deliberately unsafe plans (every gate should fire)",
}


def load_scenarios(selected: list[str] | None = None) -> list[dict[str, Any]]:
    index = json.loads((SCENARIO_ROOT / "index.json").read_text(encoding="utf-8"))
    scenarios = []
    for row in index["scenarios"]:
        if selected and row["scenario_id"] not in selected:
            continue
        path = SCENARIO_ROOT / row["scenario_id"] / "evaluator_only" / "scenario.json"
        scenarios.append(json.loads(path.read_text(encoding="utf-8")))
    return scenarios


def _failed_gates(item: dict[str, Any]) -> list[str]:
    return [g["gate"] for g in item.get("gates", []) if not g["passed"]]


def summary_markdown(runs: dict[str, list[dict[str, Any]]]) -> str:
    lines = [
        "# Evaluation results",
        "",
        "> Generated by `python -m evaluation.run_eval`. Pass rule: score >= "
        f"{scorer.PASS_SCORE}/100 **and** every safety gate holds. Rubric: "
        "[`../SCORING_SHEET.md`](../SCORING_SHEET.md).",
        "",
        "| Planner | What it is | Checkpoints passed | Scenarios passed | Mean score |",
        "|---|---|---|---|---|",
    ]
    for planner, scenario_runs in runs.items():
        cps = [cp for run in scenario_runs for cp in run["checkpoints"]]
        passed_cps = sum(cp["passed"] for cp in cps)
        passed_runs = sum(run["passed"] for run in scenario_runs)
        mean = sum(cp["score"] for cp in cps) / len(cps) if cps else 0
        lines.append(f"| `{planner}` | {PLANNER_NOTES.get(planner, '')} | {passed_cps}/{len(cps)} | "
                     f"{passed_runs}/{len(scenario_runs)} | {mean:.1f} |")
    if "live" not in runs:
        lines += ["", "**No live-planner results yet.** Run `--planner live` with "
                  "`OPENCODE_GO_API_KEY` set; until then these numbers say nothing about the "
                  "real agent."]
    for planner, scenario_runs in runs.items():
        lines += ["", f"## `{planner}`", "",
                  "| Scenario | CP | Branch | Stage | Score | Pass | Failed gates |",
                  "|---|---|---|---|---|---|---|"]
        for run in scenario_runs:
            for cp in run["checkpoints"]:
                stage = cp.get("plan", {}).get("stage", "-")
                gates = ", ".join(_failed_gates(cp)) or "-"
                lines.append(f"| {run['scenario_id']} | {cp['checkpoint']} | {cp.get('branch', '-')} | "
                             f"{stage} | {cp['score']} | {'yes' if cp['passed'] else 'no'} | {gates} |")
            system = [g["gate"] for g in run.get("system_checks", []) if not g["passed"]]
            if system:
                lines.append(f"| {run['scenario_id']} | system | | | | no | {', '.join(system)} |")
    coverage = next((run["report"]["not_produced_yet"] for rs in runs.values() for run in rs
                     if run.get("report")), [])
    if coverage:
        lines += ["", "## Not yet produced by the system (not scored)", ""]
        lines += [f"- {item}" for item in coverage]
        lines += ["", "The ground truth for these exists in each scenario's `evaluator_only/` "
                  "(ATT&CK CSV, timeline) and can be scored once the planner or report emits them."]
    return "\n".join(lines) + "\n"


def rebuild_summary() -> Path:
    runs = {}
    for planner in PLANNERS:
        path = RESULTS / f"{planner}.json"
        if path.exists():
            runs[planner] = json.loads(path.read_text(encoding="utf-8"))["runs"]
    out = RESULTS / "SUMMARY.md"
    out.write_text(summary_markdown(runs), encoding="utf-8", newline="\n")
    return out


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--planner", nargs="+", default=["fake", "oracle", "unsafe"],
                        choices=PLANNERS)
    parser.add_argument("--scenario", nargs="*", help="scenario ids (default: all)")
    parser.add_argument("--profile", default="demo", choices=["demo", "clean"])
    args = parser.parse_args(argv)

    RESULTS.mkdir(parents=True, exist_ok=True)
    scenarios = load_scenarios(args.scenario)
    exit_code = 0
    for planner in args.planner:
        runs = []
        for scenario in scenarios:
            started = time.monotonic()
            run = run_scenario(scenario, planner, args.profile)
            runs.append(run)
            marks = " ".join(f"{cp['checkpoint']}={cp['score']}{'' if cp['passed'] else '!'}"
                             for cp in run["checkpoints"])
            print(f"[{planner}] {scenario['scenario_id']}: {'PASS' if run['passed'] else 'FAIL'} "
                  f"({marks}) {time.monotonic() - started:.1f}s", file=sys.stderr)
        payload = {"planner": planner, "profile": args.profile,
                   "note": PLANNER_NOTES.get(planner, ""), "runs": runs}
        if args.scenario:
            payload["partial"] = True
        path = RESULTS / f"{planner}.json"
        path.write_text(json.dumps(payload, indent=2, ensure_ascii=False) + "\n", encoding="utf-8",
                        newline="\n")
    print(f"summary: {rebuild_summary()}", file=sys.stderr)
    return exit_code


if __name__ == "__main__":
    raise SystemExit(main())
